"""Vendor the crates that need the shared-cache permission fix, patched.

Pixi's caches (repodata, shards, conda->PyPI mapping, ...) are written through
`tempfile`, which creates files with mode 0600 regardless of the umask. When
several users share one PIXI_CACHE_DIR, everyone but the writer then gets
"Permission denied". The fix (conda/rattler#2950, plus the same change for
cacache) creates those temporary files with mode 0666 so the umask, or a
default ACL on the cache directory, decides who can read them.

On top of that, `[cache] shared = true` makes everything created in the cache
readable and writable by every user whatever the umask. `fs-err` and
`tempfile` (which uv and rattler create cache files through), uv's build
frontend and git source code, rattler's package cache and repodata locks, and
cacache call the `shared_cache_perms` helper crate for that (shared-perms.diff).

This script makes those changes apply to the exact crate versions in Cargo.lock:

1. downloads each affected crate from crates.io into patches/shared-cache/<name>,
2. applies patches/shared-cache/rattler.diff, cacache.diff and shared-perms.diff,
3. adds the rattler_shared_tempfile and shared_cache_perms helper crates as
   dependencies where needed,
4. rewrites the marked block in Cargo.toml's [patch.crates-io] to point there.
   A crate that the workspace takes from git (uv, on some pixi versions) is
   still downloaded from crates.io at the same version, but its dependencies
   on crates from that repository are pointed back at the git source, and it is
   listed in a marked [patch."<git url>"] block instead.

After rebasing onto a new pixi release, run it again and then
`cargo metadata --format-version=1 >/dev/null` to refresh Cargo.lock. If a diff no
longer applies, update the diff against the new crate version first.

Usage: python scripts/vendor_shared_cache.py
"""

import io
import re
import shutil
import subprocess
import tarfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIR = ROOT / "patches" / "shared-cache"
RATTLER_DIFF = DIR / "rattler.diff"
CACACHE_DIFF = DIR / "cacache.diff"
SHARED_PERMS_DIFF = DIR / "shared-perms.diff"
HELPER = "rattler_shared_tempfile"
PERMS_HELPER = "shared_cache_perms"
BEGIN = "# >>> shared-cache patches (generated by scripts/vendor_shared_cache.py)\n"
END = "# <<< shared-cache patches\n"
GIT_BEGIN = "# >>> shared-cache git patches (generated by scripts/vendor_shared_cache.py)\n"
GIT_END = "# <<< shared-cache git patches\n"


def workspace_git_deps() -> dict[str, dict]:
    """Workspace dependencies that come from git, by name."""
    deps = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["dependencies"]
    return {name: spec for name, spec in deps.items() if isinstance(spec, dict) and "git" in spec}


def point_at_git(dest: Path, git: dict, git_deps: dict[str, dict]) -> None:
    """Make the dependencies of a vendored crate that live in the same git repo use that repo."""
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text())
    same_repo = {n for n, s in git_deps.items() if s["git"] == git["git"]} | {
        pkg["name"] for pkg in lock["package"] if pkg.get("source", "").startswith(f"git+{git['git']}?")
    }
    pin = "".join(f'{key} = "{git[key]}"\n' for key in ("git", "tag", "rev", "branch") if key in git)
    toml = dest / "Cargo.toml"

    def repl(m: re.Match) -> str:
        return m.group(0) + pin if m.group(2) in same_repo else m.group(0)

    toml.write_text(re.sub(r'^(\[(?:dev-|build-)?dependencies\.([\w-]+)\]\nversion = "[^"]*"\n)',
                           repl, toml.read_text(), flags=re.M))


def replace_block(text: str, begin: str, end: str, block: str, anchor: str | None) -> str:
    if begin in text:
        return re.sub(re.escape(begin) + r".*?" + re.escape(end), lambda _: block, text, flags=re.S)
    if anchor is None:
        return text.rstrip("\n") + "\n\n" + block if block else text
    return text.replace(anchor, anchor + block, 1)


def locked_version(name: str) -> str:
    """The single version of `name` in Cargo.lock (from crates.io, or vendored by an earlier run)."""
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text())
    found = {pkg["version"] for pkg in lock["package"] if pkg["name"] == name}
    if len(found) != 1:
        raise SystemExit(f"expected exactly one locked version of {name}, found {sorted(found)}")
    return found.pop()


def vendor(name: str, version: str) -> Path:
    dest = DIR / name
    shutil.rmtree(dest, ignore_errors=True)
    url = f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
    with urllib.request.urlopen(url) as resp:
        data = resp.read()
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tf:
        tf.extractall(DIR, filter="data")
    (DIR / f"{name}-{version}").rename(dest)
    for junk in ("Cargo.toml.orig", ".cargo_vcs_info.json", "Cargo.lock"):
        (dest / junk).unlink(missing_ok=True)
    print(f"vendored {name} {version}")
    return dest


def add_dependency(dest: Path, helper: str) -> None:
    with (dest / "Cargo.toml").open("a") as f:
        f.write(f'\n[dependencies.{helper}]\nversion = "0.1.0"\npath = "../{helper}"\n')


def apply(diff: Path, strip: int, cwd: Path) -> None:
    subprocess.run(["patch", f"-p{strip}", "--forward", "--no-backup-if-mismatch", "-i", str(diff)],
                   cwd=cwd, check=True)


def main() -> None:
    rattler_crates = sorted(set(re.findall(r"^diff --git a/crates/([^/]+)/", RATTLER_DIFF.read_text(), re.M)))

    for name in rattler_crates:
        add_dependency(vendor(name, locked_version(name)), HELPER)
    apply(RATTLER_DIFF, 2, DIR)  # a/crates/<name>/src/... -> <name>/src/...

    vendor("cacache", locked_version("cacache"))
    apply(CACACHE_DIFF, 1, DIR / "cacache")

    perms_crates = sorted(set(re.findall(r"^diff -ruN a/([^/]+)/", SHARED_PERMS_DIFF.read_text(), re.M)))
    extra_crates = [name for name in perms_crates if name not in (*rattler_crates, "cacache")]
    for name in extra_crates:
        vendor(name, locked_version(name))
    for name in perms_crates:
        add_dependency(DIR / name, PERMS_HELPER)
    apply(SHARED_PERMS_DIFF, 1, DIR)  # a/<name>/src/... -> <name>/src/...

    git_deps = workspace_git_deps()
    from_git: dict[str, list[str]] = {}
    for name in extra_crates:
        if name in git_deps:
            point_at_git(DIR / name, git_deps[name], git_deps)
            from_git.setdefault(git_deps[name]["git"], []).append(name)

    def entry(n: str) -> str:
        return f'{n} = {{ path = "patches/shared-cache/{n}" }}\n'

    crates_io = [n for n in [*rattler_crates, "cacache", *extra_crates] if n not in git_deps]
    git_block = "".join(f'[patch."{url}"]\n' + "".join(map(entry, names)) for url, names in from_git.items())
    toml_path = ROOT / "Cargo.toml"
    text = toml_path.read_text()
    text = replace_block(text, BEGIN, END, BEGIN + "".join(map(entry, crates_io)) + END, "[patch.crates-io]\n")
    text = replace_block(text, GIT_BEGIN, GIT_END, GIT_BEGIN + git_block + GIT_END if git_block else "", None)
    toml_path.write_text(text)
    print("updated [patch.crates-io] in Cargo.toml; now refresh Cargo.lock: cargo metadata --format-version=1 >/dev/null")


if __name__ == "__main__":
    main()
